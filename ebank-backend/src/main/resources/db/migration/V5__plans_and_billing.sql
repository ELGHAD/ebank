-- SaaS plans, subscriptions, usage counters and SIMULATED billing (no payment provider, no card data).

-- Plans are reference data. A null limit means "unlimited".
create table plan (
    code                    varchar(20)    primary key,
    name                    varchar(60)    not null,
    monthly_price           numeric(19, 2) not null,
    currency                varchar(3)     not null,
    max_staff               integer,
    max_clients             integer,
    max_accounts            integer,
    max_transfers_per_month integer,
    sort_order              integer        not null,
    constraint ck_plan_price check (monthly_price >= 0),
    constraint ck_plan_limits check (coalesce(max_staff, 1) > 0 and coalesce(max_clients, 1) > 0
        and coalesce(max_accounts, 1) > 0 and coalesce(max_transfers_per_month, 1) > 0)
);

insert into plan (code, name, monthly_price, currency, max_staff, max_clients, max_accounts, max_transfers_per_month, sort_order)
values ('FREE', 'Free', 0, 'EUR', 3, 25, 50, 200, 1),
       ('PRO', 'Pro', 49, 'EUR', 25, 1000, 2500, 10000, 2),
       ('ENTERPRISE', 'Enterprise', 199, 'EUR', null, null, null, null, 3);

-- One subscription per organization. PAST_DUE simulates a failed payment: growth is blocked, money stays accessible.
create table subscription (
    organization_id      bigint      primary key references organization (id),
    plan_code            varchar(20) not null references plan (code),
    status               varchar(20) not null default 'ACTIVE',
    current_period_start timestamptz not null,
    current_period_end   timestamptz not null,
    updated_at           timestamptz not null default now(),
    constraint ck_subscription_status check (status in ('ACTIVE', 'PAST_DUE')),
    constraint ck_subscription_period check (current_period_end > current_period_start)
);

-- Existing organizations start on the free plan
insert into subscription (organization_id, plan_code, current_period_start, current_period_end)
select id, 'FREE', now(), now() + interval '1 month' from organization;

-- Invariant enforced by the database, whatever the code path: every organization has a subscription
create function create_default_subscription() returns trigger
    language plpgsql as
$$
begin
    insert into subscription (organization_id, plan_code, current_period_start, current_period_end)
    values (new.id, 'FREE', now(), now() + interval '1 month');
    return new;
end;
$$;

create trigger trg_organization_default_subscription
    after insert on organization
    for each row execute function create_default_subscription();

-- Simulated invoices: one per organization and billing period (idempotent renewal), never modified
create table invoice (
    id              bigint generated by default as identity primary key,
    organization_id bigint         not null references organization (id),
    plan_code       varchar(20)    not null references plan (code),
    period_start    timestamptz    not null,
    period_end      timestamptz    not null,
    amount          numeric(19, 2) not null,
    currency        varchar(3)     not null,
    created_at      timestamptz    not null default now(),
    constraint uk_invoice_period unique (organization_id, period_start),
    constraint ck_invoice_amount check (amount >= 0)
);
create index ix_invoice_organization on invoice (organization_id, id desc);

create trigger trg_invoice_append_only
    before update or delete on invoice
    for each row execute function forbid_update_or_delete();

-- Monthly transfer counter, incremented in the transfer's own transaction (rolled back with it)
create table usage_counter (
    organization_id bigint  not null references organization (id),
    period_month    date    not null,
    transfers       integer not null default 0,
    primary key (organization_id, period_month),
    constraint ck_usage_counter_non_negative check (transfers >= 0)
);

-- Least privilege (see V3): the application may only read plans, and may not rewrite invoices
do
$$
    declare
        app_db_role text := '${appDbUser}';
    begin
        if app_db_role <> current_user and exists (select 1 from pg_roles where rolname = app_db_role) then
            execute format('revoke insert, update, delete on plan from %I', app_db_role);
            execute format('revoke update, delete on invoice from %I', app_db_role);
        end if;
    end
$$;
