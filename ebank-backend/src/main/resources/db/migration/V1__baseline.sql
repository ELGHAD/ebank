-- Baseline schema for the eBank banking simulation (PostgreSQL).
-- Flyway owns the schema; Hibernate only validates it (spring.jpa.hibernate.ddl-auto=validate).

create table organization (
    id         bigint generated by default as identity primary key,
    name       varchar(120) not null,
    created_at timestamptz  not null default now(),
    constraint uk_organization_name unique (name)
);

create table app_role (
    id        bigint generated by default as identity primary key,
    role_name varchar(40) not null,
    constraint uk_app_role_name unique (role_name)
);

-- Login identity. username is the user's email address (lower-cased) and is unique platform-wide.
-- organization_id is nullable so that future platform-level administrators can exist outside any tenant.
create table app_user (
    id              bigint generated by default as identity primary key,
    organization_id bigint       references organization (id),
    username        varchar(254) not null,
    password_hash   varchar(100) not null,
    enabled         boolean      not null default true,
    created_at      timestamptz  not null default now(),
    constraint uk_app_user_username unique (username)
);
create index ix_app_user_organization on app_user (organization_id);

create table user_role (
    user_id bigint not null references app_user (id) on delete cascade,
    role_id bigint not null references app_role (id),
    primary key (user_id, role_id)
);

create table client (
    id              bigint generated by default as identity primary key,
    organization_id bigint       not null references organization (id),
    app_user_id     bigint       not null references app_user (id),
    identity_ref    varchar(50)  not null,
    first_name      varchar(100) not null,
    last_name       varchar(100) not null,
    birth_date      date,
    address         varchar(255),
    created_at      timestamptz  not null default now(),
    constraint uk_client_app_user unique (app_user_id),
    constraint uk_client_identity_ref unique (organization_id, identity_ref),
    -- Target of the composite foreign key below.
    constraint uk_client_id_organization unique (id, organization_id)
);

create table bank_account (
    id              bigint generated by default as identity primary key,
    organization_id bigint        not null references organization (id),
    client_id       bigint        not null,
    rib             varchar(34)   not null,
    currency        varchar(3)    not null,
    balance         numeric(19, 2) not null default 0,
    status          varchar(20)   not null default 'ACTIVE',
    created_at      timestamptz   not null default now(),
    constraint uk_bank_account_rib unique (rib),
    -- An account can only belong to a client of the same organization.
    constraint fk_bank_account_client foreign key (client_id, organization_id)
        references client (id, organization_id),
    constraint ck_bank_account_currency check (currency ~ '^[A-Z]{3}$'),
    constraint ck_bank_account_status check (status in ('ACTIVE', 'BLOCKED', 'CLOSED')),
    -- Overdrafts are not part of the domain; this is a last line of defence behind the service checks.
    constraint ck_bank_account_balance_non_negative check (balance >= 0)
);
create index ix_bank_account_client on bank_account (client_id);
create index ix_bank_account_organization on bank_account (organization_id);

