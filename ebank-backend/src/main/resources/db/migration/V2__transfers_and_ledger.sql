-- Transfer engine: completed transfers and an append-only ledger.
--
-- Invariants:
--   * a transfer row exists only for a completed transfer (processing is synchronous; failures leave no rows);
--   * each transfer has exactly one DEBIT and one CREDIT ledger entry of the same amount;
--   * bank_account.balance = sum(DEPOSIT + CREDIT) - sum(DEBIT) of its entries (checked by reconciliation);
--   * transfers and ledger entries are never updated or deleted (enforced by triggers below).

create table transfer (
    id                     bigint generated by default as identity primary key,
    organization_id        bigint         not null references organization (id),
    initiated_by_id        bigint         not null references app_user (id),
    idempotency_key        varchar(100)   not null,
    request_hash           varchar(64)    not null,
    source_account_id      bigint         not null references bank_account (id),
    destination_account_id bigint         not null references bank_account (id),
    amount                 numeric(19, 2) not null,
    currency               varchar(3)     not null,
    description            varchar(140),
    created_at             timestamptz    not null default now(),
    -- The idempotency guarantee: one transfer per (user, key), even under concurrent retries.
    constraint uk_transfer_idempotency unique (initiated_by_id, idempotency_key),
    constraint ck_transfer_amount_positive check (amount > 0),
    constraint ck_transfer_distinct_accounts check (source_account_id <> destination_account_id)
);
create index ix_transfer_source on transfer (source_account_id);
create index ix_transfer_destination on transfer (destination_account_id);

create table ledger_entry (
    id              bigint generated by default as identity primary key,
    organization_id bigint         not null references organization (id),
    account_id      bigint         not null references bank_account (id),
    transfer_id     bigint references transfer (id),
    entry_type      varchar(10)    not null,
    amount          numeric(19, 2) not null,
    balance_after   numeric(19, 2) not null,
    description     varchar(140),
    created_at      timestamptz    not null default now(),
    constraint ck_ledger_entry_type check (entry_type in ('DEPOSIT', 'DEBIT', 'CREDIT')),
    constraint ck_ledger_entry_amount_positive check (amount > 0),
    constraint ck_ledger_entry_balance_non_negative check (balance_after >= 0),
    -- Deposits are the only entries without a transfer; transfer entries always have one.
    constraint ck_ledger_entry_transfer_link check ((entry_type = 'DEPOSIT') = (transfer_id is null))
);
-- Account history is read newest first, page by page
create index ix_ledger_entry_account on ledger_entry (account_id, id desc);
create index ix_ledger_entry_transfer on ledger_entry (transfer_id);

-- Append-only enforcement at the database level, independent of application code.
create function forbid_update_or_delete() returns trigger
    language plpgsql as
$$
begin
    raise exception '% is append-only: % is not allowed', tg_table_name, tg_op;
end;
$$;

create trigger trg_transfer_append_only
    before update or delete on transfer
    for each row execute function forbid_update_or_delete();

create trigger trg_ledger_entry_append_only
    before update or delete on ledger_entry
    for each row execute function forbid_update_or_delete();

-- Backfill: balances that existed before the ledger become opening deposits, so reconciliation holds.
insert into ledger_entry (organization_id, account_id, entry_type, amount, balance_after, description, created_at)
select organization_id, id, 'DEPOSIT', balance, balance, 'Opening balance', created_at
from bank_account
where balance > 0;
