-- Security hardening: session revocation, forced password change, audit trail, least-privilege grants.

-- Incremented on logout and password change; tokens carrying an older version are rejected.
alter table app_user add column token_version integer not null default 0;

-- Set for clients onboarded with a one-time password; cleared when they choose their own.
alter table app_user add column must_change_password boolean not null default false;

-- Existing clients were onboarded with a password an agent has seen.
update app_user set must_change_password = true
where id in (select ur.user_id
             from user_role ur
                      join app_role r on r.id = ur.role_id
             where r.role_name = 'CLIENT');

create table audit_event (
    id              bigint generated by default as identity primary key,
    -- Null for events that cannot be attributed to a tenant (e.g. a failed login for an unknown user)
    organization_id bigint references organization (id),
    actor_user_id   bigint references app_user (id),
    actor_username  varchar(254),
    event_type      varchar(40)  not null,
    target          varchar(100),
    ip_address      varchar(45),
    details         varchar(255),
    created_at      timestamptz  not null default now()
);
create index ix_audit_event_organization on audit_event (organization_id, id desc);

create trigger trg_audit_event_append_only
    before update or delete on audit_event
    for each row execute function forbid_update_or_delete();

-- Least privilege. When the application connects with its own role (Docker: ebank_app) rather than the
-- schema owner that runs Flyway, that role gets data access only: no DDL, and no UPDATE/DELETE on the
-- append-only tables. Skipped when both are the same user (e.g. local development as postgres).
do
$$
    declare
        app_db_role text := '${appDbUser}';
    begin
        if app_db_role <> current_user and exists (select 1 from pg_roles where rolname = app_db_role) then
            execute format('grant usage on schema public to %I', app_db_role);
            execute format('grant select, insert, update, delete on all tables in schema public to %I', app_db_role);
            execute format('grant usage, select on all sequences in schema public to %I', app_db_role);
            execute format('revoke update, delete on transfer, ledger_entry, audit_event from %I', app_db_role);
            execute format('revoke all on flyway_schema_history from %I', app_db_role);
            -- Tables created by later migrations get the same base grants automatically
            execute format('alter default privileges in schema public grant select, insert, update, delete on tables to %I', app_db_role);
            execute format('alter default privileges in schema public grant usage, select on sequences to %I', app_db_role);
        end if;
    end
$$;
